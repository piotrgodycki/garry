/** Whether Garry has a mark for this technology (the catalog check uses it). */
export const hasTechMark = (id: string) => id in MARKS;

/** Marks drawn in near black (Next.js, Vercel, Express) take the text colour, so they show in dark mode too. */
const tone = (hex: string) => {
  const n = parseInt(hex.slice(1), 16);
  return 0.299 * (n >> 16) + 0.587 * ((n >> 8) & 255) + 0.114 * (n & 255) < 60 ? "var(--color-text-default)" : hex;
};

/** A technology's mark at text size; a technology Garry does not know shows its first letters. */
export default function TechIcon({ id, size = 14 }: { id: string; size?: number }) {
  const mark = MARKS[id] ?? mono(id.replace(/[^a-z0-9]/gi, "").slice(0, 2).toUpperCase() || "?");
  const style = { "--tone": tone(mark.hex), width: size, height: size } as CSSProperties;
  return (
    <span className="techIcon" style={style} aria-hidden="true">
      {"path" in mark ? (
        <svg viewBox="0 0 24 24" width={size} height={size} fill="currentColor">
          <path d={mark.path} />
        </svg>
      ) : "glyph" in mark ? (
        <svg viewBox="0 0 24 24" width={size} height={size} fill="currentColor">
          <path d="M13.5 2L4.5 13.5h6L9.5 22l9-11.5h-6z" />
        </svg>
      ) : (
        <span className="techMono" style={{ fontSize: Math.max(7, Math.round(size * (mark.text.length > 2 ? 0.46 : 0.6))) }}>
          {mark.text}
        </span>
      )}
    </span>
  );
}
