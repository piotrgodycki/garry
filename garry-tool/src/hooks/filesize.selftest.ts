/**
 * Regression test for the file size check: a staged file over 5,000 tokens
 * (bytes / 4) is refused and the message says how to split it; only staged
 * files count; lockfiles, generated code and binaries are skipped; garry hooks
 * check and install; and Garry refusing to commit an agent's oversized file
 * (a project setting, 0 turns it off). Run with: pnpm -C garry-tool
 * test:filesize (CI runs it too).
 */
import { execFileSync, spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const home = mkdtempSync(join(tmpdir(), "garry-filesize-"));
process.env.GARRY_HOME = join(home, ".garry");
process.env.GARRY_CLAUDE_BIN = fileURLToPath(new URL("../threads/testdata/fake-claude.mjs", import.meta.url));

const { oversizedStaged, sizeMessage, MAX_TOKENS } = await import("./filesize.js");
const { ThreadManager, FileSizeError } = await import("../threads/manager.js");
const { ThreadStore } = await import("../threads/store.js");

let failed = 0;
const expect = (name: string, ok: boolean, detail = "") => {
  console.log(`${ok ? "ok  " : "FAIL"} ${name}${ok || !detail ? "" : `: ${detail}`}`);
  if (!ok) failed++;
};
const until = async (f: () => boolean, ms = 10_000) => {
  const end = Date.now() + ms;
  while (!f() && Date.now() < end) await new Promise((r) => setTimeout(r, 50));
};

const repo = join(home, "app");
const g = (...args: string[]) => execFileSync("git", ["-C", repo, ...args], { encoding: "utf8" });
execFileSync("git", ["init", "-q", repo]);
const put = (path: string, bytes: number | string, stage = true) => {
  mkdirSync(join(repo, path, ".."), { recursive: true });
  writeFileSync(join(repo, path), typeof bytes === "string" ? bytes : "x".repeat(bytes));
  if (stage) g("add", path);
};
const names = () => oversizedStaged(repo).map((f) => `${f.path}:${f.tokens}`).sort().join(" ");

// the limit: 5,000 tokens is 20,000 bytes
put("src/at-limit.ts", 20_000);
put("src/small.ts", 100);
expect("a file of exactly 5,000 tokens passes", names() === "", names());
put("src/over.ts", 20_001);
expect("one byte more is refused, counted as bytes / 4", names() === "src/over.ts:5001", names());
expect("the limit is 5,000", MAX_TOKENS === 5000);

// only what is staged
put("src/unstaged.ts", 40_000, false);
expect("a big file that is not staged does not count", !names().includes("unstaged"));
g("reset", "-q");
g("add", "src/small.ts", "src/at-limit.ts");
g("-c", "user.name=t", "-c", "user.email=t@t", "commit", "-qm", "base");
put("src/big-before.ts", 30_000, false);
g("add", "src/big-before.ts");
g("-c", "user.name=t", "-c", "user.email=t@t", "commit", "-qm", "big", "--no-verify");
put("src/small.ts", 200);
expect("a big file already committed and not staged again does not count", names() === "", names());
g("rm", "-q", "src/big-before.ts");
let deleting = "";
try {
  deleting = names();
} catch (e) {
  deleting = String(e);
}
expect("deleting a big file is fine (it gets smaller, not bigger)", deleting === "", deleting.slice(0, 160));
g("reset", "-q");
g("checkout", "-q", "--", "src/big-before.ts");

// what nobody writes by hand is left alone
put("pnpm-lock.yaml", 90_000);
put("ios/Podfile.lock", 90_000);
put("dist/app.js", 90_000);
put("src/bundle.min.js", 90_000);
put("src/api.generated.ts", 90_000);
put("src/schema.ts", `// @generated by the schema tool\n${"x".repeat(90_000)}`);
put("src/types.go", `// Code generated by protoc. DO NOT EDIT.\n${"x".repeat(90_000)}`);
put("assets/logo.png", 90_000);
put("data/blob.dat", `ab\0cd${"x".repeat(90_000)}`);
writeFileSync(join(repo, ".gitattributes"), "src/routes.ts linguist-generated\n");
g("add", ".gitattributes");
put("src/routes.ts", 90_000);
expect("lockfiles, generated code, binaries and linguist-generated files are skipped", names() === "", names());
put("src/App.tsx", 26_000);
put("src/styles.css", 26_000);
put("docs/guide.md", 26_000);
put("config/data.json", 26_000);
expect("what people and agents write is checked, whatever its kind", names() === "config/data.json:6500 docs/guide.md:6500 src/App.tsx:6500 src/styles.css:6500", names());

// the message says how to split each kind
const msg = sizeMessage(oversizedStaged(repo));
expect("the message names every file with its size", ["src/App.tsx: about 6,500 tokens", "src/styles.css: about 6,500 tokens", "docs/guide.md: about 6,500 tokens", "config/data.json: about 6,500 tokens"].every((l) => msg.includes(l)), msg);
expect("and how many files it should become", msg.includes("(2 files of under 5,000 would hold it)"));
const section = (path: string) => msg.slice(msg.indexOf(path), msg.indexOf("\n\n", msg.indexOf(path)));
expect("a component: move components, hooks and constants into files of their own", /component[\s\S]*own[\s\S]*hooks[\s\S]*constants/i.test(section("src/App.tsx")));
expect("styles: split by section", /Split by section/.test(section("src/styles.css")));
expect("docs: a short overview and a page per section, linked", /overview[\s\S]*docs\/<topic>\.md[\s\S]*Link/.test(section("docs/guide.md")));
expect("data: one file per entry, or mark it generated", /one file per entry[\s\S]*linguist-generated/.test(section("config/data.json")));
expect("and not to cheat the limit", /Do not shorten names, strip comments or minify/.test(msg));

// the command line
const cli = fileURLToPath(new URL("../cli.ts", import.meta.url));
// tsx by its full path: the commands run inside the test's repository, far from node_modules
const tsx = import.meta.resolve("tsx");
const run = (...args: string[]) => spawnSync(process.execPath, ["--import", tsx, cli, ...args], { cwd: repo, encoding: "utf8" });
const check = run("hooks", "check");
expect("garry hooks check fails the commit and prints the message", check.status === 1 && check.stderr.includes("src/App.tsx: about 6,500 tokens"), check.stderr.slice(0, 200));
expect("--max sets another limit", run("hooks", "check", "--max", "10000").status === 0);
g("reset", "-q");
expect("nothing staged, nothing refused", run("hooks", "check").status === 0);
writeFileSync(join(repo, ".git", "hooks", "pre-commit"), "#!/bin/sh\necho mine\n");
run("hooks", "install");
run("hooks", "install");
const hook = readFileSync(join(repo, ".git", "hooks", "pre-commit"), "utf8");
expect("garry hooks install adds the check once, after the hook already there", hook.startsWith("#!/bin/sh\necho mine\n") && hook.split("garry hooks check").length === 2, hook);

// Garry refuses to commit an agent's oversized file
const threads = new ThreadManager(new ThreadStore(process.env.GARRY_HOME!));
const shop = join(home, "shop");
execFileSync("git", ["init", "-q", shop]);
writeFileSync(join(shop, "README.md"), "# shop\n");
execFileSync("git", ["-C", shop, "add", "-A"]);
execFileSync("git", ["-C", shop, "-c", "user.name=t", "-c", "user.email=t@t", "commit", "-qm", "init"]);
const project = threads.store.addProject(shop);
// the stand-in agent writes its prompt into NOTES.md: a long prompt makes a big file
const t = threads.create(project.id, `write it all down ${"word ".repeat(5000)}`);
await until(() => !threads.isRunning(t.id));
let refused: unknown = null;
try {
  threads.commit(t.id, "notes");
} catch (e) {
  refused = e;
}
const status = execFileSync("git", ["-C", t.worktree, "status", "--porcelain"], { encoding: "utf8" });
expect("Garry refuses to commit an agent's file over the limit, saying how to split it", refused instanceof FileSizeError && (refused as Error).message.includes("NOTES.md: about") && (refused as InstanceType<typeof FileSizeError>).status === 422, String(refused));
expect("and leaves the work as it was: nothing committed, nothing staged", !threads.store.get(t.id)?.commit && status.trim() !== "" && !status.split("\n").some((l) => /^[AM]/.test(l)), status);
threads.store.saveSettings(project.id, { maxFileTokens: 0 });
let done: { commit?: string } = {};
try {
  done = threads.commit(t.id, "notes");
} catch (e) {
  done = { commit: undefined };
  console.log(String(e).slice(0, 120));
}
expect("with the limit off (0) in the project's settings, it commits", !!done.commit);
let bad = false;
try {
  threads.store.saveSettings(project.id, { maxFileTokens: 12 });
} catch {
  bad = true;
}
expect("a limit too small to work with is refused", bad);

if (failed) {
  console.error(`${failed} file size check(s) failed`);
  process.exit(1);
}
console.log("The file size check behaves as expected");
process.exit(0);
