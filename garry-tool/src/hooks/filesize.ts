import { execFileSync } from "node:child_process";
import { basename, extname } from "node:path";

/**
 * Keeps the files agents write small enough for an agent to read whole: a
 * staged file over the limit (5,000 tokens, counted as bytes / 4) is refused,
 * with instructions on how to split it. Only staged files are looked at, and
 * only what people and agents write: lockfiles, generated code, minified
 * bundles and binaries are left alone, as is anything .gitattributes marks
 * linguist-generated.
 */
export const MAX_TOKENS = 5000;
export const tokensOf = (bytes: number) => Math.ceil(bytes / 4);

const LOCKFILES = new Set(["pnpm-lock.yaml", "package-lock.json", "npm-shrinkwrap.json", "yarn.lock", "bun.lockb", "bun.lock", "Cargo.lock", "poetry.lock", "Pipfile.lock", "uv.lock", "Gemfile.lock", "composer.lock", "go.sum", "flake.lock", "packages.lock.json", "Podfile.lock", "pubspec.lock", "mix.lock"]);
const BINARY = new Set([".png", ".jpg", ".jpeg", ".gif", ".webp", ".ico", ".icns", ".avif", ".pdf", ".zip", ".gz", ".tgz", ".woff", ".woff2", ".ttf", ".otf", ".eot", ".mp3", ".mp4", ".mov", ".wasm", ".jar", ".dylib", ".so", ".dll", ".exe"]);
const GENERATED_DIRS = /(^|\/)(dist|build|out|coverage|vendor|node_modules|__generated__|generated|\.next|\.expo)\//;
const GENERATED_NAMES = /\.(min\.(js|css)|map|snap|lock)$|\.(pb|generated|gen)\.\w+$|_pb2\.py$/;

export interface Oversized {
  path: string;
  tokens: number;
}

const git = (cwd: string, args: string[]) => execFileSync("git", args, { cwd, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });

/** Why a path is not looked at, or null when it is: a lockfile, generated, or not text. */
export function skipReason(path: string, head: string): string | null {
  const name = basename(path);
  if (LOCKFILES.has(name)) return "lockfile";
  if (BINARY.has(extname(name).toLowerCase())) return "binary";
  if (GENERATED_DIRS.test(path) || GENERATED_NAMES.test(name)) return "generated";
  if (head.includes("\0")) return "binary";
  // the markers code generators leave at the top of what they write
  if (/@generated|DO NOT EDIT|auto-?generated|Code generated by/i.test(head.split("\n").slice(0, 5).join("\n"))) return "generated";
  return null;
}

/** The staged files over the limit, in a repository (or a worktree of one). */
export function oversizedStaged(cwd: string, max = MAX_TOKENS): Oversized[] {
  const staged = git(cwd, ["diff", "--cached", "--name-only", "--diff-filter=ACMR", "-z"]).split("\0").filter(Boolean);
  if (!staged.length) return [];
  const generated = new Set(
    git(cwd, ["check-attr", "-z", "linguist-generated", "--", ...staged])
      .split("\0")
      .reduce<string[][]>((acc, v, i) => (i % 3 === 0 ? [...acc, [v]] : (acc[acc.length - 1].push(v), acc)), [])
      .filter(([, , value]) => value === "true" || value === "set")
      .map(([p]) => p),
  );
  const out: Oversized[] = [];
  for (const path of staged) {
    if (generated.has(path)) continue;
    const bytes = Number(git(cwd, ["cat-file", "-s", `:${path}`]).trim());
    if (tokensOf(bytes) <= max) continue;
    const head = execFileSync("git", ["cat-file", "blob", `:${path}`], { cwd, maxBuffer: 64 * 1024 * 1024 }).subarray(0, 2048).toString("utf8");
    if (skipReason(path, head)) continue;
    out.push({ path, tokens: tokensOf(bytes) });
  }
  return out;
}

/** How to split a file of this kind, in plain steps. */
function howToSplit(path: string): string[] {
  const ext = extname(path).toLowerCase();
  if ([".tsx", ".jsx", ".vue", ".svelte"].includes(ext))
    return [
      "Move each component that is not the page's own into a file of its own beside it (Card.tsx, Toolbar.tsx), and import it.",
      "Move hooks (useSomething) and plain helpers into their own modules (lib/, or a sibling file named for what they do).",
      "Move constants, tables and types into a sibling file (things.ts, types.ts).",
      "Keep the file's default export where it is, so imports elsewhere do not change.",
    ];
  if ([".ts", ".js", ".mjs", ".cjs", ".py", ".go", ".rb", ".rs", ".java", ".kt", ".swift", ".php", ".cs"].includes(ext))
    return [
      "Find the groups of functions that belong together (one concern each: routes for one resource, one parser, one client).",
      "Move each group into its own module in the same folder, named for that concern, and import it where it is used.",
      "If other files import from this one, keep a short re-export here (export { x } from \"./x\") so their imports do not change.",
      "Move types and constants shared by the new modules into a small module of their own.",
    ];
  if ([".css", ".scss", ".less"].includes(ext))
    return [
      "Split by section: the rules for one part of the page or one component go to a file of their own (a CSS module beside the component, or a partial).",
      "Keep design tokens (custom properties) and resets in the main file; @import or import the parts where they are used.",
    ];
  if ([".md", ".mdx", ".rst", ".txt"].includes(ext))
    return [
      "Keep a short overview here and move each long section into its own page (docs/<topic>.md).",
      "Link to the new pages from where the sections were, so nothing is lost.",
    ];
  if ([".json", ".yaml", ".yml", ".toml"].includes(ext))
    return [
      "Split the data into one file per entry or per group (a folder of small files) and load them together.",
      "If a tool writes this file, it is generated: mark it in .gitattributes (path linguist-generated) instead of splitting it.",
    ];
  return ["Split it by responsibility into smaller files, each about one thing, and link or import them from where this one is used."];
}

/** The error a commit gets: every file over the limit, and how to split each one. */
export function sizeMessage(files: Oversized[], max = MAX_TOKENS): string {
  const lines = [
    `Commit refused: ${files.length === 1 ? "a file is" : `${files.length} files are`} over ${max.toLocaleString("en")} tokens (counted as bytes / 4).`,
    "Agents read whole files; past this size they skim, miss things and edit the wrong place. Split each file below into smaller ones that each do one thing:",
    "",
  ];
  for (const f of files) {
    lines.push(`  ${f.path}: about ${f.tokens.toLocaleString("en")} tokens (${Math.ceil(f.tokens / max)} files of under ${max.toLocaleString("en")} would hold it)`);
    for (const step of howToSplit(f.path)) lines.push(`    - ${step}`);
    lines.push("");
  }
  lines.push(
    "Then stage the new files and commit again. Do not shorten names, strip comments or minify to get under the limit; split by what the code does.",
    "A file a tool writes (not a person or an agent) is skipped: mark it in .gitattributes, for example: path/to/file linguist-generated",
  );
  return lines.join("\n");
}
