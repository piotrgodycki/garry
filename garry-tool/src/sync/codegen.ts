import type { Contracts, Manifest } from "./registryIO.js";

/** Maps a payload field type written in a contract to a TypeScript type. */
function tsType(v: string): string {
  switch (v) {
    case "string":
      return "string";
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    default:
      return "unknown";
  }
}

/**
 * Generates a .d.ts from the contract slice:
 * - GarryEvents: a map from event name to its payload shape.
 * - RemoteModule: a union of the modules this service may import, from consumes.
 * - SharedDepName: a union of the shared dependency names.
 */
export function generateContractTypes(manifest: Manifest, slice: Contracts): string {
  const lines: string[] = [
    "// Generated by garry sync. Do not edit by hand.",
    "// Types derived from the contract slice for this service.",
    "",
  ];

  lines.push("export interface GarryEvents {");
  for (const [name, ev] of Object.entries(slice.events ?? {})) {
    const fields = Object.entries(ev.payload)
      .map(([k, t]) => `${JSON.stringify(k)}: ${tsType(t)}`)
      .join("; ");
    lines.push(`  ${JSON.stringify(name)}: { ${fields} };`);
  }
  lines.push("}");
  lines.push("export type GarryEventName = keyof GarryEvents;");
  lines.push("");

  const modules: string[] = [];
  for (const [svc, mods] of Object.entries(manifest.consumes ?? {})) {
    for (const m of mods) modules.push(`${svc}/${m.replace(/^\.\//, "")}`);
  }
  if (modules.length) {
    lines.push("export type RemoteModule =");
    lines.push(modules.map((m) => `  | ${JSON.stringify(m)}`).join("\n") + ";");
  } else {
    lines.push("export type RemoteModule = never;");
  }
  lines.push("");

  const shared = Object.keys(slice.sharedDeps ?? {});
  if (shared.length) {
    lines.push("export type SharedDepName =");
    lines.push(shared.map((s) => `  | ${JSON.stringify(s)}`).join("\n") + ";");
  } else {
    lines.push("export type SharedDepName = never;");
  }
  lines.push("");

  return lines.join("\n");
}
